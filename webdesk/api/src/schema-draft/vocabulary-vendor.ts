// WSK-32 — the vocabulary constants + Layer-2 composition validator the AI drafting flow checks
// every proposal against (webdesk/delivery/vocabulary/{primitives,blocks,composition,version}.ts).
//
// Why not a direct import of webdesk/delivery/vocabulary: webdesk/api/src/codegen/contract-manifest.types.ts
// documents the constraint — the NestJS api is plain commonjs, compiled by `tsc -p tsconfig.json`,
// and the vocabulary files use ESM `.ts`-extension relative imports among themselves, which `tsc`
// under `"module": "commonjs"` cannot resolve without `allowImportingTsExtensions` (a flag that
// forces `noEmit: true` and would break `npm run build`).
//
// WSK-64 (vocabulary 1.1.0): this file USED to be a hand transcription of composition.ts, guarded
// only by a constants drift check, so a rule change (new FieldDef keys, group nesting, the field-name
// grammar, the `fields` block ban) could never reach it except by hand. It now RE-EXPORTS the api's
// one mechanically vendored copy, ../delivery/vocabulary/ (generated by that directory's vendor.mjs
// and byte-checked by test/delivery/vocabulary-vendor-drift.spec.ts). The import surface is
// unchanged for ./prompt.ts, ./diff-summary.ts and ./schema-draft.service.ts, with one deliberate
// narrowing: `BlockType`/`BLOCK_TYPE_NAMES` here mean the block types a COMPOSITION may list — the 9
// generic blocks. The composition-typed `fields` block is never proposed in `blocks` (it is implied
// by declaring `fields`), so it is not offered to the model.
//
// test/schema-draft/vendor-drift.spec.ts still reads the real source as TEXT and checks the
// constants, and also checks that the validator re-exported here IS the vendored one.

