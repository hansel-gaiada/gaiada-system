-- webdesk/migrations/0013_preview_tokens.sql
-- WSK-46 (WebDesk M3, draft preview), owner ruling WSK-D52: a draft preview is an instant page ON THE
-- SITE that fetches the draft from WebDesk with a short-lived token and renders it with the site's own
-- components. This table is the token store. The control plane mints a token for one VERSION of one
-- content item (content.previewToken); the public route GET /v1/t/:tenantSlug/preview/:token reads it.
--
-- THE TOKEN IS A BEARER CAPABILITY. Anyone holding the link sees that one version until it expires or
-- is revoked. So the plaintext is never stored: 32 random bytes, base64url, generated by the api; only
-- its sha256 (lowercase hex) lands here. The public route looks the row up BY that hash (an exact-match
-- lookup on the unique index is the comparison; plaintext is never compared). There is deliberately no
-- pepper: the input has 256 bits of entropy, so a keyed hash adds nothing, and an unkeyed one keeps the
-- lookup reproducible by the one reader that has no secret configuration.
--
-- A row pins ONE (content_item_id, version). The composite foreign key to content_versions makes a token
-- for a version that does not exist unrepresentable, and content_versions is append-only for the app
-- role, so a pinned version can never change under a live token. expires_at is mandatory (no
-- never-expiring token); revoked_at is set by content.previewTokenRevoke. A row is never deleted (the
-- app role has no DELETE): the table is also the record of which draft was exposed, to whom it was
-- minted for (created_by is the editorial principal's sub) and for how long.
--
-- RLS and grants follow 0002/0009/0012 exactly: FORCE ROW LEVEL SECURITY with the single-mode
-- tenant_isolation policy (every row belongs to exactly one tenant, no platform_ctx escape), fail-closed
-- on an unset webdesk.tenant_ctx. The public route resolves the tenant from the URL slug first and then
-- reads under that tenant's own tenant_ctx, so a token minted for tenant A can never be seen, let alone
-- served, under tenant B's slug.
--
-- No DML runs here (nothing to backfill), so this file is clear of the RLS zero-row trap
-- (lint-migration-rls.mjs). It is re-runnable: every statement is IF NOT EXISTS / DROP IF EXISTS.
-- Runs as webdesk_migrator (no SET ROLE) in the runner's per-file transaction, like every earlier file.

CREATE TABLE IF NOT EXISTS preview_tokens (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id       uuid NOT NULL REFERENCES tenants(id),
  site_id         uuid NOT NULL REFERENCES sites(id),
  content_item_id uuid NOT NULL REFERENCES content_items(id),
  version         integer NOT NULL CHECK (version >= 1),
  token_hash      text NOT NULL,          -- sha256(token) as 64 lowercase hex chars; the plaintext is never stored
  expires_at      timestamptz NOT NULL,
  created_by      text NOT NULL,          -- opaque principal (EditorialPrincipal.sub), attribution only
  created_at      timestamptz NOT NULL DEFAULT now(),
  revoked_at      timestamptz,
  CONSTRAINT preview_tokens_token_hash_check
    CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  CONSTRAINT preview_tokens_expiry_check
    CHECK (expires_at > created_at),
  CONSTRAINT preview_tokens_version_fk
    FOREIGN KEY (content_item_id, version) REFERENCES content_versions (content_item_id, version)
);

-- The lookup the public route does: exactly one row per hash, across the table.
CREATE UNIQUE INDEX IF NOT EXISTS ux_preview_tokens_hash ON preview_tokens (token_hash);

-- Expiry sweeps and "what is still live" reads: only rows that are neither revoked nor spent.
CREATE INDEX IF NOT EXISTS ix_preview_tokens_expires ON preview_tokens (expires_at) WHERE revoked_at IS NULL;

CREATE INDEX IF NOT EXISTS ix_preview_tokens_tenant ON preview_tokens (tenant_id);
CREATE INDEX IF NOT EXISTS ix_preview_tokens_item ON preview_tokens (content_item_id);

-- Grants. The default-privilege rule in init-roles.sh would hand the app role SELECT/INSERT/UPDATE/
-- DELETE on a new table; say it explicitly and take DELETE back (the table is history). UPDATE is for
-- the single revoked_at transition.
REVOKE ALL ON preview_tokens FROM webdesk_app;
GRANT SELECT, INSERT, UPDATE ON preview_tokens TO webdesk_app;

ALTER TABLE preview_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE preview_tokens FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON preview_tokens;
CREATE POLICY tenant_isolation ON preview_tokens FOR ALL
  USING      (tenant_id = webdesk_tenant_ctx())
  WITH CHECK (tenant_id = webdesk_tenant_ctx());
