#!/usr/bin/env bash
# M6 P5 gate -- a REAL WordPress renders entirely from WebDesk's /v1.
#
# Stands up, in throwaway containers on one private docker network (no host ports, no host paths
# except a scratch dir for the docker build context):
#
#   Postgres (init-roles.sh) + Redis + RustFS (digest-pinned)     as webdesk/qa/linux-gate.sh
#   the WebDesk api, BUILT FROM THE TREE                          docker build -f webdesk/api/Dockerfile webdesk
#   a seeded test tenant ("pages" collection, vocabulary blocks, an unknown block type, a javascript:
#     CTA, items home/about/contact in en+id) and ONE production read key
#   the tenant's contract generated LIVE by the image's compiled generator; sdk.php read back from RustFS
#   wordpress:php8.3-apache + mysql:8.4 + wordpress:cli (all digest-pinned) with the gaiada-webdesk theme,
#     the tenant's generated sdk.php vendored over the fixture one, and the GAIADA_WEBDESK_* constants
#
# ...then curls the site from inside the WordPress container and asserts what comes back. See the
# "Assertions" block below, and webdesk/wordpress/README.md ("The P5 gate").
#
# Usage:   bash p5-wp-gate.sh <run-id> <source.tar>
#   The tar MUST come from:  git -c core.autocrlf=false archive --format=tar <ref>
#   (a Windows checkout has CRLF blobs, which break init-roles.sh).
# Logs:    ~/wg-p5-<id>/*.log on the host running this script.
# Last stdout line is exactly "### done <id> PASS" or "### done <id> FAIL"; exit 0 only on PASS.
#
# Do NOT run this on a box that is already loaded (it builds the api image, ~2 min of CPU) and never on
# production. On sumopod:
#   git -c core.autocrlf=false archive --format=tar <ref> | ssh sumopod 'cat > ~/wg-p5-<id>.tar'
#   scp webdesk/qa/p5-wp-gate.sh sumopod:~/p5-wp-gate.sh
#   ssh sumopod 'nohup bash ~/p5-wp-gate.sh <id> ~/wg-p5-<id>.tar > ~/wg-p5-<id>.out 2>&1 & echo started'
#   then poll:  ssh sumopod 'tail -3 ~/wg-p5-<id>.out'   until a "### done <id> ..." line appears.
#
# Everything secret here (the DB passwords, the pepper, the read key) is a throwaway that exists only
# inside this run; the read key is generated by seed.mjs, captured into a shell variable, and never printed.
set -euo pipefail
export MSYS_NO_PATHCONV=1 MSYS2_ARG_CONV_EXCL='*'   # Git Bash must not rewrite container paths

ID="${1:-}"; TAR="${2:-}"
if [ -z "$ID" ] || [ -z "$TAR" ]; then
  echo "usage: bash p5-wp-gate.sh <run-id> <source.tar>"
  echo "### done ${ID:-?} FAIL"; exit 2
fi
case "$ID" in *[!a-zA-Z0-9_.-]*) echo "SETUP FAILED: run-id must match [a-zA-Z0-9_.-]"; echo "### done $ID FAIL"; exit 2;; esac

P="wg-p5-$ID"
NET="$P"; VOL="$P-src"
PG="$P-pg"; REDIS="$P-redis"; RUSTFS="$P-rustfs"; API="$P-api"; MYSQL="$P-mysql"; WP="$P-wp"; RUNNER="$P-runner"
API_IMG="$P-api:run"
LOGDIR="$HOME/wg-p5-$ID"
mkdir -p "$LOGDIR"
CTX=""   # host scratch dir holding the extracted webdesk/ tree (docker build context); removed in the trap

# Same images linux-gate.sh uses (reused verbatim) ...
NODE_IMG="node:22-bookworm"
RUSTFS_IMG="rustfs/rustfs:1.0.0@sha256:8cc9801755448b71a786705ce76692c77e14936cccd87cf2fc31842e58f4d1ff"
# ... plus the WordPress side. Digests = the multi-arch index digest of the tag, read from the Docker Hub
# registry API (HEAD /v2/library/<repo>/manifests/<tag>, header Docker-Content-Digest) on 2026-10-12.
WP_IMG="wordpress:php8.3-apache@sha256:f32ffa85064d9c951b7b69c929fa2a9f682aa4443e0c0a56ac2000499cb64383"
MYSQL_IMG="mysql:8.4@sha256:6ea90827b1100f8f2ae306a539f86d2c264a26ed435a2a9f75551dd5c3aeb242"
WPCLI_IMG="wordpress:cli@sha256:36243da432a0f0a3b56dc3240ecee9b159108d71305e7c064d987a20a465bfde"

APP_URL="postgres://webdesk_app:throwaway_app@$PG:5432/webdesk"
MIG_URL="postgres://webdesk_migrator:throwaway_migrator@$PG:5432/webdesk"
SUPER_URL="postgres://postgres:throwaway_superuser@$PG:5432/webdesk"
STORAGE_ENDPOINT="http://$RUSTFS:9000"
RUSTFS_ROOT_USER=webdesk_root
RUSTFS_ROOT_PASSWORD=ci-throwaway-root-password
PEPPER=ci-throwaway-pepper
TENANT_SLUG=p5-gate
WP_DB_NAME=wp; WP_DB_USER=wp; WP_DB_PASS=p5-throwaway-wp-db-pass; WP_DB_ROOT=p5-throwaway-mysql-root
WP_ADMIN_PASS=p5-throwaway-wp-admin-pass

OVERALL=PASS
CHECKS=0; PASSED=0; FAILED=0
KEY=""

cleanup() {
  set +e
  echo "--- teardown"
  if [ "$OVERALL" != PASS ]; then   # leave evidence in the log dir before the containers go
    for c in "$API" "$WP" "$PG" "$MYSQL" "$RUSTFS"; do docker logs "$c" > "$LOGDIR/container-${c#$P-}.log" 2>&1; done
  fi
  docker rm -fv "$WP" "$MYSQL" "$API" "$RUSTFS" "$REDIS" "$PG" "$RUNNER" >/dev/null 2>&1
  docker network rm "$NET" >/dev/null 2>&1
  docker volume rm -f "$VOL" >/dev/null 2>&1
  docker rmi -f "$API_IMG" >/dev/null 2>&1
  [ -n "$CTX" ] && rm -rf "$CTX"
  echo "--- summary (run $ID, logs in $LOGDIR)"
  echo "checks=$CHECKS passed=$PASSED failed=$FAILED"
  echo "### done $ID $OVERALL"
  [ "$OVERALL" = PASS ] && exit 0 || exit 1
}
trap cleanup EXIT

setup_failed() { echo "SETUP FAILED: $*"; OVERALL=FAIL; exit 1; }

# ---- sanity + source ----------------------------------------------------------------------------
[ -f "$TAR" ] || setup_failed "source tar not found: $TAR"
docker info >/dev/null 2>&1 || setup_failed "docker daemon not reachable"
echo "run $ID  tar=$TAR  tenant=$TENANT_SLUG"
docker network create "$NET" >/dev/null || setup_failed "docker network create failed"
docker volume create "$VOL" >/dev/null || setup_failed "docker volume create failed"
docker run --rm -i -v "$VOL:/src" alpine tar -x -C /src < "$TAR" || setup_failed "untar into volume failed"
docker run --rm -v "$VOL:/src" alpine test -f /src/webdesk/postgres/init-roles.sh \
  || setup_failed "tar has no webdesk/postgres/init-roles.sh (wrong archive?)"
if docker run --rm -v "$VOL:/src" alpine grep -q "$(printf '\r')" /src/webdesk/postgres/init-roles.sh; then
  setup_failed "init-roles.sh has CRLF -- build the tar with: git -c core.autocrlf=false archive --format=tar <ref>"
fi
for f in qa/p5-wp-gate/seed.mjs qa/p5-wp-gate/generate.mjs wordpress/theme/gaiada-webdesk/functions.php api/Dockerfile; do
  docker run --rm -v "$VOL:/src" alpine test -f "/src/webdesk/$f" || setup_failed "tar has no webdesk/$f"
done
# The api build context is ./webdesk (M6-P4r-a), on the host: extract just that subtree.
CTX="$(mktemp -d "$LOGDIR/ctx.XXXXXX")"
tar -x -C "$CTX" -f "$TAR" webdesk || setup_failed "could not extract webdesk/ for the docker build context"
chmod -R a+rX "$CTX"

# ---- 1. services (as linux-gate.sh) + mysql ------------------------------------------------------
echo "=== starting services"
docker run -d --name "$PG" --network "$NET" \
  -e POSTGRES_PASSWORD=throwaway_superuser -e POSTGRES_DB=webdesk \
  -e POSTGRES_OWNER_USER=webdesk_owner -e POSTGRES_OWNER_PASSWORD=throwaway_owner \
  -e POSTGRES_MIGRATOR_USER=webdesk_migrator -e POSTGRES_MIGRATOR_PASSWORD=throwaway_migrator \
  -e POSTGRES_APP_USER=webdesk_app -e POSTGRES_APP_PASSWORD=throwaway_app \
  -v "$VOL:/src:ro" --entrypoint sh postgres:16-alpine \
  -c 'cp /src/webdesk/postgres/init-roles.sh /docker-entrypoint-initdb.d/10-init-roles.sh && chmod +x /docker-entrypoint-initdb.d/10-init-roles.sh && exec docker-entrypoint.sh postgres' \
  >/dev/null || setup_failed "could not start postgres"
docker run -d --name "$REDIS" --network "$NET" redis:7-alpine >/dev/null || setup_failed "could not start redis"
docker run -d --name "$RUSTFS" --network "$NET" -e "RUSTFS_ROOT_USER=$RUSTFS_ROOT_USER" \
  -e "RUSTFS_ROOT_PASSWORD=$RUSTFS_ROOT_PASSWORD" "$RUSTFS_IMG" >/dev/null || setup_failed "could not start rustfs"
docker run -d --name "$MYSQL" --network "$NET" \
  -e "MYSQL_ROOT_PASSWORD=$WP_DB_ROOT" -e "MYSQL_DATABASE=$WP_DB_NAME" -e "MYSQL_USER=$WP_DB_USER" -e "MYSQL_PASSWORD=$WP_DB_PASS" \
  "$MYSQL_IMG" >/dev/null || setup_failed "could not start mysql"

# ---- 2. the api image, built from the tree -------------------------------------------------------
echo "=== building the api image (docker build -f webdesk/api/Dockerfile webdesk)"
if ! docker build -q -t "$API_IMG" -f "$CTX/webdesk/api/Dockerfile" "$CTX/webdesk" > "$LOGDIR/api-build.log" 2>&1; then
  tail -n 25 "$LOGDIR/api-build.log" | sed 's/^/    /'
  setup_failed "api image build failed, see $LOGDIR/api-build.log"
fi

ok=0; for i in $(seq 1 60); do
  docker exec "$PG" pg_isready -h 127.0.0.1 -U webdesk_owner -d webdesk >/dev/null 2>&1 && { ok=1; break; }; sleep 1; done
[ "$ok" = 1 ] || { docker logs "$PG" 2>&1 | tail -20; setup_failed "postgres never became ready"; }
ok=0; for i in $(seq 1 30); do docker exec "$REDIS" redis-cli ping >/dev/null 2>&1 && { ok=1; break; }; sleep 1; done
[ "$ok" = 1 ] || setup_failed "redis never became ready"
ok=0; for i in $(seq 1 30); do
  docker exec "$RUSTFS" curl -sf http://127.0.0.1:9000/health >/dev/null 2>&1 && { ok=1; break; }; sleep 1; done
[ "$ok" = 1 ] || { docker logs "$RUSTFS" 2>&1 | tail -20; setup_failed "rustfs never became healthy"; }

# ---- 3. storage bootstrap + migrations (as linux-gate.sh's prep) ---------------------------------
echo "=== prep (npm ci, storage bootstrap, migrate)"
if ! docker run --rm --name "$RUNNER" --network "$NET" -v "$VOL:/src" -w /src/webdesk/api \
  -e CI=true -e FORCE_COLOR=0 -e NO_COLOR=1 \
  -e "RUSTFS_ROOT_USER=$RUSTFS_ROOT_USER" -e "RUSTFS_ROOT_PASSWORD=$RUSTFS_ROOT_PASSWORD" \
  -e "STORAGE_ENDPOINT=$STORAGE_ENDPOINT" -e STORAGE_ACCESS_KEY_ID=webdesk_api \
  -e STORAGE_SECRET_ACCESS_KEY=ci-throwaway-api-secret-key -e STORAGE_BUCKET_MEDIA=media \
  -e STORAGE_BUCKET_VIDEO=video -e STORAGE_BUCKET_UPLOADS=uploads -e STORAGE_BUCKET_ARTIFACTS=artifacts \
  -e "MIGRATE_DATABASE_URL=$MIG_URL" "$NODE_IMG" \
  bash -c 'set -eo pipefail; npm ci && node ../scripts/storage-bootstrap.mjs && cd /src/webdesk && npm ci && npm run migrate' \
  > "$LOGDIR/prep.log" 2>&1; then
  tail -n 15 "$LOGDIR/prep.log" | sed 's/^/    /'
  setup_failed "prep (npm ci / storage-bootstrap / migrate) failed, see $LOGDIR/prep.log"
fi

# ---- 4. the WebDesk api, run as shipped ----------------------------------------------------------
# NODE_ENV is left UNSET on purpose: "test" would swap the real control-plane guards for header stubs.
# Scheduler, contract-codegen trigger, mail and the Zone B event bridge are off: nothing here needs them,
# and the contract is generated explicitly below. The api gets ONLY the service storage key, never root.
API_ENV=(
  -e "APP_DATABASE_URL=$APP_URL" -e "REDIS_URL=redis://$REDIS:6379"
  -e "STORAGE_ENDPOINT=$STORAGE_ENDPOINT" -e STORAGE_ACCESS_KEY_ID=webdesk_api
  -e STORAGE_SECRET_ACCESS_KEY=ci-throwaway-api-secret-key
  -e STORAGE_BUCKET_MEDIA=media -e STORAGE_BUCKET_VIDEO=video -e STORAGE_BUCKET_UPLOADS=uploads -e STORAGE_BUCKET_ARTIFACTS=artifacts
  -e "API_KEY_PEPPER=$PEPPER"
  -e TENANT_WEBHOOK_SECRET_PEPPER=ci-throwaway-webhook-pepper
  -e WEBDESK_EVENT_SECRET=ci-throwaway-event-secret
  -e WEBDESK_APPROVAL_ASSERTION_KEY=ci-throwaway-ws4-key
  -e MAIL_ENABLED=false -e WEBDESK_SCHEDULER_ENABLED=false
  -e WEBDESK_CONTRACT_CODEGEN_ENABLED=false -e WEBDESK_ZONEB_EVENTS_ENABLED=false
  -e WEBDESK_READ_QUOTA_PER_MIN=100000
)
echo "=== starting the api"
docker run -d --name "$API" --network "$NET" "${API_ENV[@]}" "$API_IMG" >/dev/null || setup_failed "could not start the api container"
# The api has no health route; "up" = it answers HTTP on :3000 (any status).
api_up() { docker exec "$API" node -e "fetch('http://127.0.0.1:3000/v1/t/none/pages/none').then(()=>process.exit(0),()=>process.exit(1))" >/dev/null 2>&1; }
ok=0; for i in $(seq 1 60); do
  [ "$(docker inspect -f '{{.State.Running}}' "$API" 2>/dev/null)" = true ] || break
  api_up && { ok=1; break; }; sleep 1; done
[ "$ok" = 1 ] || { docker logs "$API" 2>&1 | tail -30; setup_failed "the api never answered on :3000"; }

# ---- 5. seed the tenant + mint the read key ------------------------------------------------------
echo "=== seeding tenant $TENANT_SLUG"
SEED_OUT="$(docker run --rm -i --network "$NET" -w /app \
  -e "SEED_DATABASE_URL=$SUPER_URL" -e "SEED_PEPPER=$PEPPER" -e "SEED_TENANT_SLUG=$TENANT_SLUG" \
  --entrypoint node "$API_IMG" --input-type=module - < "$CTX/webdesk/qa/p5-wp-gate/seed.mjs" 2> "$LOGDIR/seed.log")" \
  || { tail -n 20 "$LOGDIR/seed.log" | sed 's/^/    /'; setup_failed "seeding failed, see $LOGDIR/seed.log"; }
KEY="${SEED_OUT#P5KEY=}"
case "$KEY" in wdsk_*) ;; *) setup_failed "seed did not return a read key";; esac
cat "$LOGDIR/seed.log"

# ---- 6. generate the contract LIVE, read sdk.php back from RustFS --------------------------------
echo "=== generating the contract (compiled generator in the api image) and reading sdk.php back from RustFS"
docker run --rm -i --network "$NET" -w /app "${API_ENV[@]}" -e "GEN_TENANT_SLUG=$TENANT_SLUG" \
  --entrypoint node "$API_IMG" --input-type=module - < "$CTX/webdesk/qa/p5-wp-gate/generate.mjs" \
  > "$LOGDIR/sdk.php" 2> "$LOGDIR/generate.log" \
  || { tail -n 25 "$LOGDIR/generate.log" | sed 's/^/    /'; setup_failed "contract generation failed, see $LOGDIR/generate.log"; }
cat "$LOGDIR/generate.log"
chmod 644 "$LOGDIR/sdk.php"
SDK_SHA="$(sha256sum "$LOGDIR/sdk.php" | cut -d' ' -f1)"
echo "sdk.php sha256=$SDK_SHA ($(wc -c < "$LOGDIR/sdk.php") bytes)"

# ---- 7. WordPress --------------------------------------------------------------------------------
echo "=== waiting for mysql"
ok=0; for i in $(seq 1 90); do
  # TCP on purpose: during image init the temporary server listens on the socket only.
  docker exec "$MYSQL" mysql -h127.0.0.1 -u"$WP_DB_USER" -p"$WP_DB_PASS" "$WP_DB_NAME" -e 'select 1' >/dev/null 2>&1 && { ok=1; break; }; sleep 2; done
[ "$ok" = 1 ] || { docker logs "$MYSQL" 2>&1 | tail -20; setup_failed "mysql never became ready"; }

echo "=== starting wordpress"
WPENV=(-e "WORDPRESS_DB_HOST=$MYSQL" -e "WORDPRESS_DB_USER=$WP_DB_USER" -e "WORDPRESS_DB_PASSWORD=$WP_DB_PASS" -e "WORDPRESS_DB_NAME=$WP_DB_NAME")
# The theme reads these constants from wp-config.php (inc/config.php); the official image writes
# WORDPRESS_CONFIG_EXTRA into wp-config.php on first start.
WP_EXTRA="define('GAIADA_WEBDESK_BASE_URL', 'http://$API:3000');
define('GAIADA_WEBDESK_TENANT', '$TENANT_SLUG');
define('GAIADA_WEBDESK_API_KEY', '$KEY');
define('GAIADA_WEBDESK_LOCALES', 'en,id');"
docker run -d --name "$WP" --network "$NET" "${WPENV[@]}" -e "WORDPRESS_CONFIG_EXTRA=$WP_EXTRA" "$WP_IMG" >/dev/null \
  || setup_failed "could not start wordpress"
ok=0; for i in $(seq 1 60); do
  docker exec "$WP" sh -c 'test -f /var/www/html/wp-config.php && test -f /var/www/html/wp-includes/version.php' >/dev/null 2>&1 && { ok=1; break; }; sleep 1; done
[ "$ok" = 1 ] || { docker logs "$WP" 2>&1 | tail -20; setup_failed "wordpress files/wp-config.php never appeared"; }
docker exec "$WP" sh -c 'command -v curl >/dev/null' || setup_failed "no curl inside the wordpress image (the assertions curl from there)"

echo "=== vendoring the theme and the generated sdk.php"
tar -c --owner=0 --group=0 --numeric-owner -C "$CTX/webdesk/wordpress/theme" gaiada-webdesk | docker cp - "$WP:/var/www/html/wp-content/themes/" \
  || setup_failed "docker cp of the theme failed"
SDK_STAGE="$(mktemp -d "$LOGDIR/sdk.XXXXXX")"; cp "$LOGDIR/sdk.php" "$SDK_STAGE/sdk.php"; chmod 755 "$SDK_STAGE"; chmod 644 "$SDK_STAGE/sdk.php"
tar -c --owner=0 --group=0 --numeric-owner -C "$SDK_STAGE" sdk.php \
  | docker cp - "$WP:/var/www/html/wp-content/themes/gaiada-webdesk/vendor/gaiada-sdk/" || setup_failed "docker cp of sdk.php failed"
rm -rf "$SDK_STAGE"
docker exec "$WP" php -l /var/www/html/wp-content/themes/gaiada-webdesk/vendor/gaiada-sdk/sdk.php >/dev/null || setup_failed "vendored sdk.php does not lint"

# wp-cli shares the WordPress container's files and DB env (wp-config.php reads WORDPRESS_DB_* from the env).
wpcli() { docker run --rm --network "$NET" --volumes-from "$WP" --user 33:33 "${WPENV[@]}" "$WPCLI_IMG" wp "$@"; }
echo "=== wp core install / theme activate"
{
  wpcli core install --url="http://$WP" --title="P5 Gate" --admin_user=admin --admin_password="$WP_ADMIN_PASS" \
    --admin_email=p5@example.test --skip-email \
  && wpcli theme activate gaiada-webdesk \
  && wpcli rewrite structure '/%postname%/' --hard \
  && wpcli rewrite flush --hard
} > "$LOGDIR/wp-install.log" 2>&1 || { tail -n 20 "$LOGDIR/wp-install.log" | sed 's/^/    /'; setup_failed "wp-cli install/activate failed, see $LOGDIR/wp-install.log"; }
ACTIVE="$(wpcli theme list --status=active --field=name 2>>"$LOGDIR/wp-install.log" | tr -d '\r')"
# WordPress's OWN content: a native post and a native page that collides with a WebDesk slug.
POST_ID="$(wpcli post create --post_title='WP native post' --post_name=wp-native-post --post_status=publish \
  --post_content='WPPOST-MARKER-NATIVE' --porcelain 2>>"$LOGDIR/wp-install.log" | tr -d '\r')"
PAGE_ID="$(wpcli post create --post_type=page --post_title='About (WP)' --post_name=about --post_status=publish \
  --post_content='WPPAGE-ABOUT-LEAK' --porcelain 2>>"$LOGDIR/wp-install.log" | tr -d '\r')"
POST_URL="$(wpcli post get "$POST_ID" --field=url 2>>"$LOGDIR/wp-install.log" | tr -d '\r')"
POST_PATH="/${POST_URL#http://$WP/}"
echo "wp: active theme=$ACTIVE  post id=$POST_ID url=$POST_URL  colliding page id=$PAGE_ID"

# ---- assertions ----------------------------------------------------------------------------------
ST=""; BODY=""
ok() { CHECKS=$((CHECKS+1)); PASSED=$((PASSED+1)); echo "PASS  $1"; }
bad() { CHECKS=$((CHECKS+1)); FAILED=$((FAILED+1)); OVERALL=FAIL; echo "FAIL  $1"; [ -z "${2:-}" ] || echo "      $2"; }
# req <path> [curl args]: GET http://<wordpress>/<path> from INSIDE the wordpress container.
req() {
  local path="$1"; shift
  ST="$(docker exec "$WP" curl -s -o /tmp/p5body -w '%{http_code}' --max-time 60 "$@" "http://$WP$path" 2>/dev/null)" || ST=000
  BODY="$(docker exec "$WP" cat /tmp/p5body 2>/dev/null || true)"
}
is_status() { if [ "$ST" = "$2" ]; then ok "$1 -> HTTP $2"; else bad "$1 -> HTTP $2" "got HTTP $ST; body starts: $(printf '%s' "$BODY" | head -c 300 | tr '\n' ' ')"; fi; }
has() { if printf '%s' "$BODY" | grep -qF -- "$2"; then ok "$1"; else bad "$1" "body does not contain: $2"; fi; }
lacks() { if printf '%s' "$BODY" | grep -qF -- "$2"; then bad "$1" "body contains (must not): $2"; else ok "$1"; fi; }

echo "=== assertions"
if [ "$ACTIVE" = gaiada-webdesk ]; then ok "the gaiada-webdesk theme is the active theme"; else bad "the gaiada-webdesk theme is the active theme" "active: $ACTIVE"; fi
if [ "$(docker exec "$WP" sha256sum /var/www/html/wp-content/themes/gaiada-webdesk/vendor/gaiada-sdk/sdk.php | cut -d' ' -f1)" = "$SDK_SHA" ]; then
  ok "the theme's vendor/gaiada-sdk/sdk.php is the tenant's generated one (sha256 matches the object read from RustFS)"
else bad "the theme's vendor/gaiada-sdk/sdk.php is the tenant's generated one"; fi

# /v1 itself (positive control + tenancy negatives), from the WordPress container, through the api.
V1="http://$API:3000/v1/t/$TENANT_SLUG/pages/home?locale=en"
ST="$(docker exec "$WP" curl -s -o /tmp/p5body -w '%{http_code}' --max-time 30 -H "Authorization: Bearer $KEY" "$V1")" || ST=000
BODY="$(docker exec "$WP" cat /tmp/p5body)"
is_status "/v1 pages/home with the read key" 200
has "/v1 envelope carries the seeded hero heading" "P5GATE-HOME-EN-HERO"
ST="$(docker exec "$WP" curl -s -o /dev/null -w '%{http_code}' --max-time 30 "$V1")" || ST=000
is_status "/v1 pages/home with NO key" 401
ST="$(docker exec "$WP" curl -s -o /dev/null -w '%{http_code}' --max-time 30 -H "Authorization: Bearer $KEY" "http://$API:3000/v1/t/some-other-tenant/pages/home?locale=en")" || ST=000
is_status "/v1 of ANOTHER tenant slug with this tenant's key (tenancy wall)" 401

# 1. /  -> the home item, default locale en
req /
is_status "GET /" 200
has "/ has <html lang=\"en\">" '<html lang="en">'
has "/ renders the home hero heading" '<h1>P5GATE-HOME-EN-HERO</h1>'
has "/ uses the item's seo title" '<title>P5GATE Home EN</title>'
has "/ hero CTA keeps a safe relative href" 'href="/about/"'
for b in hero richtext cta gallery featuregrid testimonial faq logocloud; do
  has "/ renders the known block gaiada-block-$b" "gaiada-block-$b"
done
# the unknown block type: renders nothing, leaks nothing, breaks nothing around it
lacks "/ renders nothing for the unknown block type (no 'pricingTable')" 'pricingTable'
lacks "/ leaks none of the unknown block's props" 'P5GATE-PRICING-LEAK'
lacks "/ leaks none of the unknown block's nested props" 'P5GATE-PLAN-LEAK'
has "/ the known block AFTER the unknown one still renders (richText)" 'P5GATE-HOME-EN-RICH'
has "/ the known block BEFORE the unknown one still renders (hero sub)" 'P5GATE-HOME-EN-SUB'
has "/ the LAST known block still renders (logoCloud)" 'P5GATE-HOME-EN-LOGOS'
# a javascript: CTA href seeded in content
lacks "/ has no javascript: URL anywhere" 'javascript:'
has "/ the seeded javascript: CTA href renders as #" '<a href="#">Go</a>'
lacks "/ never echoes the api key" "$KEY"
lacks "/ serves none of WordPress's own default content" 'Hello world!'

# 2. /about/ -> the about item (a WordPress PAGE with the slug 'about' exists and must lose)
req /about/
is_status "GET /about/" 200
has "/about/ renders the about hero heading" '<h1>P5GATE-ABOUT-EN-HERO</h1>'
has "/about/ has <html lang=\"en\">" '<html lang="en">'
lacks "/about/ is not the colliding WordPress page" 'WPPAGE-ABOUT-LEAK'
req /about
is_status "GET /about (no trailing slash)" 200
has "/about renders the about hero heading" 'P5GATE-ABOUT-EN-HERO'

# the third slug
req /contact/
is_status "GET /contact/" 200
