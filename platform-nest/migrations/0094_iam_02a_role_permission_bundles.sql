-- 0094_iam_02a_role_permission_bundles.sql — IAM-02a: seed every built-in role as a permission
-- bundle in the (until 0093, dead) `role_permissions` table.
--
-- ── SOURCE OF TRUTH AND METHOD ───────────────────────────────────────────────────────────────────
-- Bundles are derived from the ACTUAL Cerbos policies (`cerbos/policies/resource_*.yaml` +
-- `derived_roles.yaml`), not from `platform-ui/src/lib/rbac.ts`. Every resource-policy rule was
-- parsed (real YAML parse, not regex) and `*` actions were wildcard-expanded against each kind's
-- own full action set (`permission-catalog.json`'s 230 concrete `(cerbosKind, cerbosAction)`
-- pairs — the same universe IAM-01b/01c already froze). A role "reaches" a pair if ANY allow rule
-- names it (directly, or via the module-string-composition / it_staff / hr_people_* groupings
-- below) for that action — the same "can this role reach this action in principle" abstraction
-- `docs/superpowers/plans/2026-08-10-iam-01a-02a-analysis.md` Part 4 and the drift register both
-- use (resource-instance conditions — inTenant, notLow/assurance, self-ownership — are treated as
-- "the request satisfies them", exactly like the prior analyses; that is why `member`'s count below
-- includes self-scoped actions such as `hr.case.create`/`hr.case.cancel` and `reports.appraisal.ack`
-- alongside its unconditional ones). Independently cross-checked against every published number in
-- the analysis doc's Part 4 table (platform_admin 215/57, company_admin 199/55, group_executive
-- 118/35, manager 109, member 74, team_lead 60, viewer 30, client 6, it_staff 3, module_approver 1,
-- hr_people_ops 5, hr_people_reader 5, module_staff 34, module_manager 56) — every one reproduced
-- exactly. class='relationship' permissions (the 15 assistant/mcp_tool exemptions, Ruling 3) are
-- NEVER inserted into any bundle below, and 0093's `role_permissions_reject_relationship` trigger
-- enforces that at the DB layer even if this file's own SELECT ever tried to (it does not).
--
-- ── COUPLING WITH 0093 (IAM-01c) ─────────────────────────────────────────────────────────────────
-- This file does not read or duplicate 0093_iam_permission_catalog.sql's own DDL/DML — it only
-- depends on the CONTRACT that migration establishes: `permissions.key` populated 1:1 from
-- `permission-catalog.json`. Every bundle row below is inserted by JOINing on `permissions.key`,
-- so a typo'd key here simply fails to join (caught by the per-role count assertions at the bottom,
-- not assumed away).
--
-- ── MODULE-COMPOSED ROLES: RESOLVING `module_staff`/`module_manager`/`module_approver` ───────────
-- `derived_roles.yaml` string-composes these three from `resource.attr.module` at request time
-- (Ruling 5's WSD-2 trick), so a policy file alone never names a concrete role. Resolved here by
-- reading which `module:` attribute value each resource kind's callers actually pass (grepped
-- controllers, not assumed):
--   hr_case, hr_record                              -> module "hr"      (module_staff=hr_staff, module_manager=hr_manager)
--   resource_search_{property,campaign,engagement,   -> module "search"  (module_staff=search_staff, module_manager=search_manager)
--     keyword,ledger,audit,report}
--   report_document (module_staff/manager rule ONLY  -> module "reports" (module_staff=reports_staff, module_manager=reports_manager)
--     — its own condition hardcodes `attr.module == "reports"`, verified by direct read)
--   automation_approval (module_manager rule ONLY    -> module "hr" ONLY, hardcoded in the rule's own
--     — hardcodes `attr.module == "hr"` in the rule           condition, NOT resource-generic — a
--       condition itself, verified by direct read)             first parser pass over-attributed this
--                                                                to search_manager/reports_manager; the
--                                                                drift register's own §0 correction
--                                                                flags the identical mistake, confirmed
--                                                                independently here.
--   service_assignment (`read`), member (`read`)     -> GENERIC (no module hardcode in the rule) —
--     any module_staff/module_manager-composed role reaches these for its own module's context
--     (service_assignment's own `module_key` attribute; member's `?module=` query passthrough,
--     `core.controller.ts`'s WSD-4 comment). Bundled onto ALL THREE currently-seeded module_staff/
--     module_manager pairs (hr_*, search_*, reports_*).
--   webdev_change_request, webdev_provisioned_site   -> module "webdev" — but NO `webdev_staff`/
--     (module_staff AND module_manager rules present)   `webdev_manager` role exists in the `roles`
--                                                        table (no migration, no seed script seeds
--                                                        them). These 7 (kind,action) pairs are real
--                                                        Cerbos reach for module_staff/module_manager
--                                                        but currently UNCLAIMABLE by any real role —
--                                                        flagged as a NEW provisioning gap (sibling to
--                                                        IAM-02d/0091's search_staff/search_manager
--                                                        finding and IAM-02e/0095's baseline-role
--                                                        finding), NOT fixed here (out of this
--                                                        ticket's remit — no ticket authorizes minting
--                                                        a `webdev_staff`/`webdev_manager` role).
--   module_approver                                  -> the only live instance is `agency_approval`
--     (agency_approval:approve only)                    (module "agency") -> real role `agency_approver`.
--
-- ── ROLE ROWS THIS FILE MUST SELF-SEED (idempotent, same idiom as 0026/0069/0072/0091/0095) ──────
-- role_permissions needs a role_id, and this migration (0094) runs BEFORE 0095 in filename order —
-- so IAM-02e's six baseline roles (member/manager/company_admin/platform_admin/group_executive/
-- it_admin) do NOT exist yet at the point this file executes on a fresh, migration-only database.
-- Depending on 0095 having already run would be an ordering assumption this repo has been burned by
-- before (migration-idioms-that-lie); instead this file guarantees its own dependency, using the
-- IDENTICAL `INSERT ... SELECT ... WHERE NOT EXISTS` idiom already established by every prior
-- role-seeding migration (backed by 0073's `roles_global_name_uniq` partial index, so this is safe
-- to run whether or not 0095 has landed, and 0095 landing afterward is a harmless no-op against the
-- same guard). `hr_staff`/`hr_manager` (0026), `reports_staff`/`reports_manager` (0069), `client`
-- (0072), and `team_lead`/`viewer`/`it_manager`/`it`/`search_staff`/`search_manager` (0091) are all
-- numerically BEFORE 0094 and therefore guaranteed already present — not re-seeded here.
-- `agency_approver` is a SEPARATE, NEW finding: no migration ANYWHERE seeds it (confirmed by
-- grepping every `migrations/*.sql` for the literal string) — it has existed, live, on
-- gda-aicenter ONLY because `npm run seed:agency` created it by hand. That is the exact same
-- provisioning-gap shape 0095's own header describes for the six baseline roles, just not counted
-- in that ticket's list of six. Seeded here because this migration is what first needs the row to
-- exist for a real, live-held role (drift register finding #1) — not a scope grab on IAM-02e; noted
-- for a follow-up ticket in this ticket's own report.
INSERT INTO roles (id, company_id, name, description)
SELECT gen_random_uuid(), NULL, r.name, r.description
FROM (VALUES
  ('platform_admin',   'Global superadmin — the platform-wide Cerbos wildcard (''*'') bypass rule present on ~57 of 61 resource kinds (215/230 concrete pairs; the 15 relationship-class exemptions are bypass-exempt by design, Ruling 3).'),
  ('company_admin',    'Company-scoped administrator — near-universal reach within one company (199/230 pairs, 55/61 kinds); does not span companies.'),
  ('group_executive',  'Global cross-company executive — narrower than company_admin in enforcement (118/230 pairs, 35/61 kinds); several deliberate Cerbos exclusions vs the rbac.ts ''ALL'' mirror (D-7, IAM phase 1) are documented, not fixed, here.'),
  ('manager',          'Company-scoped operational lead (109/230 pairs, 41/61 kinds); excluded from cross-cutting approval decisions Cerbos reserves for company_admin/group_executive/module_manager/module_approver (DR-1).'),
  ('member',           'Baseline company-scoped contributor (74/230 pairs, 34/61 kinds, incl. self-scoped actions like hr.case.create/cancel).'),
  ('it_admin',         'Company-scoped IT operator tier — identical Cerbos reach to it_manager/it (resource_device.yaml is the only policy reading any of the three; 3/230 pairs).')
) AS r(name, description)
WHERE NOT EXISTS (
  SELECT 1 FROM roles WHERE company_id IS NULL AND name = r.name
);

INSERT INTO roles (id, company_id, name, description)
SELECT gen_random_uuid(), NULL, 'agency_approver',
  'agency module_approver (WSD-2) — approves agency_approval requests (1/230 pairs). NEW FINDING (IAM-02a): no migration has ever seeded this role; it has existed live ONLY via the manual seed:agency script (drift-register finding #1''s single live holder). Same provisioning-gap shape as IAM-02e''s six baseline roles, seeded here because role_permissions needs the row.'
WHERE NOT EXISTS (
  SELECT 1 FROM roles WHERE company_id IS NULL AND name = 'agency_approver'
);

