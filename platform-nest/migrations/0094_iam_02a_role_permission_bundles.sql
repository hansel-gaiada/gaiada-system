-- ── Assert, don't assume ──────────────────────────────────────────────────────────────────────────
-- Per-role exact-count check catches both (a) a typo'd role name or permission key that silently
-- dropped a row from the JOIN, and (b) a double-count from an unexpectedly-duplicated global role
-- row. Total-count check is redundant with the sum of the per-role checks but kept as a cheap
-- top-level tripwire, matching 0093/0095's own "assert the exact post-seed shape" idiom.
DO $$
DECLARE
  expected record;
  got integer;
  total_expected integer := 925;
  total_got integer;
  leaked integer;
BEGIN
  FOR expected IN
    SELECT * FROM (VALUES
      ('platform_admin', 215),
      ('company_admin', 199),
      ('group_executive', 118),
      ('manager', 109),
      ('member', 74),
      ('viewer', 30),
      ('team_lead', 60),
      ('client', 6),
      ('it_admin', 3),
      ('it_manager', 3),
      ('it', 3),
      ('agency_approver', 1),
      ('hr_staff', 13),
      ('hr_manager', 23),
      ('search_staff', 24),
      ('search_manager', 37),
      ('reports_staff', 4),
      ('reports_manager', 3)
    ) AS x(role_name, expected_count)
  LOOP
    SELECT count(*) INTO got
      FROM role_permissions rp
      JOIN roles r ON r.id = rp.role_id
     WHERE r.company_id IS NULL AND r.name = expected.role_name;
    IF got <> expected.expected_count THEN
      RAISE EXCEPTION '0094: role "%": expected % bundled permissions, found %',
        expected.role_name, expected.expected_count, got;
    END IF;
  END LOOP;

  SELECT count(*) INTO total_got
    FROM role_permissions rp
    JOIN roles r ON r.id = rp.role_id
   WHERE r.company_id IS NULL
     AND r.name IN ('platform_admin','company_admin','group_executive','manager','member','viewer',
                    'team_lead','client','it_admin','it_manager','it','agency_approver',
                    'hr_staff','hr_manager','search_staff','search_manager',
                    'reports_staff','reports_manager');
  IF total_got <> total_expected THEN
    RAISE EXCEPTION '0094: total bundled permissions across the 18 built-in roles: expected %, found %',
      total_expected, total_got;
  END IF;

  -- Defense-in-depth re-assertion of Ruling 3, redundant with 0093's DB trigger: no bundle may ever
  -- contain a class='relationship' permission.
  SELECT count(*) INTO leaked
    FROM role_permissions rp
    JOIN permissions p ON p.id = rp.permission_id
   WHERE p.class = 'relationship';
  IF leaked <> 0 THEN
    RAISE EXCEPTION '0094: % relationship-class permission(s) leaked into role_permissions — Ruling 3 violated', leaked;
  END IF;

  RAISE NOTICE '0094: role_permissions seeded — % rows across 18 built-in roles, 0 relationship-class leaks', total_got;
END $$;
