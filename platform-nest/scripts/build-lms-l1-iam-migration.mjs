// One-shot generator for `migrations/<ts>_iam_lms_l1_permissions.sql`.
//
// Same reasoning as scripts/build-hr-full-iam-migration.mjs: the VALUES blocks are a TRANSCRIPTION
// of permission-catalog.json and role-permission-bundles.json, and a hand-typed transcription drifts
// from its source by one row and passes every test that does not compare them.
//
//   node scripts/build-lms-l1-iam-migration.mjs
//
// Not wired into `npm run` — the migration is written once and frozen. A later catalog change is a
// NEW migration, never a re-run of this one against an applied file.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = "migrations/202608241340_iam_lms_l1_permissions.sql";
const NEW_KEY = /^lms\./;

const catalog = JSON.parse(readFileSync(join(ROOT, "src/rbac/permission-catalog.json"), "utf8"));
const bundlesFile = JSON.parse(readFileSync(join(ROOT, "src/rbac/role-permission-bundles.json"), "utf8"));
const bundles = bundlesFile.roles ?? bundlesFile;

const sq = (s) => `'${String(s).replace(/'/g, "''")}'`;

function wrapLiteral(text, indent = "   ") {
  const words = String(text).split(" ");
  const lines = [];
  let cur = "";
  for (const w of words) {
    if ((cur + " " + w).length > 76) { lines.push(cur); cur = w; }
    else cur = cur ? `${cur} ${w}` : w;
  }
  if (cur) lines.push(cur);
  return lines.map((l, i) => sq(i === lines.length - 1 ? l : `${l} `)).join(`\n${indent}`);
}

const perms = catalog.permissions.filter((p) => NEW_KEY.test(p.key)).sort((a, b) => a.key.localeCompare(b.key));
if (perms.length !== 12) throw new Error(`expected 12 lms permissions, catalog has ${perms.length}`);

const permValues = perms.map((p) =>
  `  (${sq(p.key)}, 'lms', ${sq(p.resource)}, ${sq(p.action)},\n` +
  `   ${wrapLiteral(p.description)},\n` +
  `   ${sq(p.cerbosKind)}, ${sq(p.cerbosAction)}, 'grantable', ${p.sensitive}, ${p.uiGrantable})`,
).join(",\n");

// Every role the generator resolves for these keys. `member` INCLUDED — same precedent as 0094's
// hr_case and HR-FULL: the bundler credits a self-scoped rule as reach, the marker distinguishes it,
// and the safety argument is the ABSENT perm_* mirror rather than an absent row.
const SEED_ROLES = [
  "member", "lms_staff", "lms_manager", "org_unit_lead",
  "hr_staff", "hr_manager", "company_admin", "platform_admin", "owner",
];
const selfScopedPairs = new Set(
  Object.entries(bundlesFile.selfScoped ?? {}).flatMap(([role, keys]) => keys.map((k) => `${role}|${k}`)),
);
const bundleRows = [];
for (const role of SEED_ROLES) {
  for (const key of (bundles[role] ?? []).filter((k) => NEW_KEY.test(k)).sort()) {
    bundleRows.push(`  (${sq(role)}, ${sq(key)}, ${selfScopedPairs.has(`${role}|${key}`)})`);
  }
}
if (!bundleRows.length) throw new Error("no lms bundle rows resolved — did gen:role-bundles run?");

const header = `-- LMS L1 — the IAM half: two new roles, twelve permissions, and their bundles.
--
-- GENERATED by scripts/build-lms-l1-iam-migration.mjs from src/rbac/permission-catalog.json and
-- src/rbac/role-permission-bundles.json. Frozen once applied.
--
-- Schema for the module itself is 202608241322_module_lms_l1.sql. Design:
-- docs/blueprints/lms-foundation.md.
--
-- ══ 1 · WHY TWO NEW ROLES, AND WHY THEY MUST BE SEEDED ═════════════════════════════════════════
-- \`lms_staff\` and \`lms_manager\`. Every other module in the estate has this pair (hr, monitoring,
-- reports, search, social, webdev — verified against the live \`roles\` table 2026-08-24), and
-- \`service-reconciler.ts::moduleRoleId\` materializes \`\${moduleKey}_\${kind}\` GENERICALLY — but it
-- returns NULL if the role is unseeded, and then silently materializes nothing.
--
-- So referencing \`module_staff\` on an lms kind WITHOUT seeding these two would produce exactly the
-- defect derived_roles.yaml warns about by name: "an unreachable tier written into a contract" — a
-- policy nobody can ever satisfy, failing silently rather than loudly. Seeding them is two rows and
-- it makes LMS a first-class module like the other six, including the shared-service path if a
-- group training function ever serves LMS to another company.
--
-- ══ 2 · THE TWO KINDS ══════════════════════════════════════════════════════════════════════════
--   lms_course      the authored catalogue. READ IS DELIBERATELY WIDE (every member) — training you
--                   cannot see is a support ticket, the same reasoning resource_hr_policy.yaml
--                   records for holiday calendars. Authoring is scoped to the DEPARTMENT HEAD via
--                   \`org_unit_lead\`'s existing unitAncestors containment; no new role was needed
--                   for the owner's "each HOD makes more" requirement.
--   lms_enrollment  the OPPOSITE posture: a learner's progress, scores and FAILED attempts are
--                   personal data about a named person. Three tiers — the learner over their own,
--                   the department head over their unit, HR/admin company-wide for compliance.
--
-- Two actions are deliberately NOT folded into \`update\`, and both would be real defects if they
-- were: \`grade\` (else a learner grades themselves) and \`waive\` (excusing somebody from mandatory
-- training is a compliance decision, not an assessment — and a department head must not be able to
-- excuse their whole team from the company's mandatory track).
--
-- ══ 3 · ROLE-ARM ONLY. No perm_* mirror, for either kind. ══════════════════════════════════════
-- Same posture as HR-FULL's three kinds and resource_employee.yaml (P2-02), and here it is
-- load-bearing: every non-admin rule is ATTRIBUTE-GATED — \`subjectUserId\` self on lms_enrollment,
-- \`unitAncestors\` containment on both. A flat permission mirror can express neither, and would
-- collapse "your own progress" into "everybody's progress" and "your own department's curriculum"
-- into "every department's". That is the granularity gap resource_hr_case.yaml documents at length.
--
-- ══ 4 · \`owner\` must be mirrored explicitly ════════════════════════════════════════════════════
-- 202608221409_iam14_owner_role.sql seeded \`owner\` as a ONE-TIME snapshot of company_admin's rows;
-- later keys do NOT propagate, and owner-role.db.test.ts asserts the two match EXACTLY. None of
-- these twelve falls on that migration's documented exclusions.
--
-- ⚠ CERBOS DOES NOT HOT-RELOAD. Two new resource_*.yaml files; restart it and PROVE a decision with
--   a probe. A healthy container has served stale policy in this estate before.

-- ══════════════════════════════════════════════════════════════════════════════════════════════
-- 1 · The two module roles. ON CONFLICT DO NOTHING so a re-run is inert.
-- ══════════════════════════════════════════════════════════════════════════════════════════════
INSERT INTO roles (id, company_id, name, description)
SELECT gen_random_uuid(), NULL, v.name, v.description
FROM (VALUES
  ('lms_staff',
   'LMS staff — reads the catalogue and the training register for a company. The baseline tier, '
   'mirroring hr_staff/search_staff. Materialized by service-reconciler.ts for a served company.'),
  ('lms_manager',
   'LMS manager — the ACTING tier: authors, publishes and retires courses, assigns paths, grades '
   'reviewed submissions. Mirrors hr_manager/search_manager.')
) AS v(name, description)
WHERE NOT EXISTS (SELECT 1 FROM roles r WHERE r.company_id IS NULL AND r.name = v.name);

-- ══════════════════════════════════════════════════════════════════════════════════════════════
-- 2 · Catalog permissions. ON CONFLICT (key) DO UPDATE so a re-run syncs metadata without churning
--     the id that role_permissions rows reference (0117's idiom).
-- ══════════════════════════════════════════════════════════════════════════════════════════════
INSERT INTO permissions (id, key, module_key, resource, action, description, cerbos_kind, cerbos_action, class, sensitive, ui_grantable)
SELECT gen_random_uuid(), v.key, v.module_key, v.resource, v.action, v.description, v.cerbos_kind, v.cerbos_action, v.class, v.sensitive, v.ui_grantable
FROM (VALUES
${permValues}
) AS v(key, module_key, resource, action, description, cerbos_kind, cerbos_action, class, sensitive, ui_grantable)
ON CONFLICT (key) DO UPDATE SET
  module_key = EXCLUDED.module_key, resource = EXCLUDED.resource, action = EXCLUDED.action,
  description = EXCLUDED.description, cerbos_kind = EXCLUDED.cerbos_kind,
  cerbos_action = EXCLUDED.cerbos_action, class = EXCLUDED.class,
  sensitive = EXCLUDED.sensitive, ui_grantable = EXCLUDED.ui_grantable;

-- ══════════════════════════════════════════════════════════════════════════════════════════════
-- 3 · Role bundles, carrying the 0114 self-scoped marker per row.
-- ══════════════════════════════════════════════════════════════════════════════════════════════
INSERT INTO role_permissions (role_id, permission_id, self_scoped)
SELECT r.id, p.id, bundle.self_scoped
FROM (VALUES
${bundleRows.join(",\n")}
) AS bundle(role_name, perm_key, self_scoped)
JOIN roles r ON r.company_id IS NULL AND r.name = bundle.role_name
JOIN permissions p ON p.key = bundle.perm_key
ON CONFLICT (role_id, permission_id) DO UPDATE SET self_scoped = EXCLUDED.self_scoped;

-- ══════════════════════════════════════════════════════════════════════════════════════════════
-- 4 · Self-check. Floors where later growth is legitimate; equalities only where the header argues
--     for one.
-- ══════════════════════════════════════════════════════════════════════════════════════════════
DO $$
DECLARE
  n_roles  integer;
  n_perm   integer;
  n_bundle integer;
  n_owner  integer;
  n_ca     integer;
  n_waive  integer;
BEGIN
  SELECT count(*) INTO n_roles FROM roles WHERE company_id IS NULL AND name IN ('lms_staff','lms_manager');
  IF n_roles <> 2 THEN
    RAISE EXCEPTION 'LMS-L1: expected lms_staff + lms_manager to exist, found %', n_roles;
  END IF;

  SELECT count(*) INTO n_perm FROM permissions WHERE key LIKE 'lms.%';
  IF n_perm <> ${perms.length} THEN
    RAISE EXCEPTION 'LMS-L1: expected ${perms.length} lms permissions, found %', n_perm;
  END IF;

  SELECT count(*) INTO n_bundle FROM role_permissions rp
    JOIN permissions p ON p.id = rp.permission_id WHERE p.key LIKE 'lms.%';
  IF n_bundle < ${bundleRows.length} THEN
    RAISE EXCEPTION 'LMS-L1: expected at least ${bundleRows.length} bundle rows, found %', n_bundle;
  END IF;

  SELECT count(*) INTO n_owner FROM role_permissions rp
    JOIN permissions p ON p.id = rp.permission_id JOIN roles r ON r.id = rp.role_id
   WHERE r.company_id IS NULL AND r.name = 'owner' AND p.key LIKE 'lms.%';
  SELECT count(*) INTO n_ca FROM role_permissions rp
    JOIN permissions p ON p.id = rp.permission_id JOIN roles r ON r.id = rp.role_id
   WHERE r.company_id IS NULL AND r.name = 'company_admin' AND p.key LIKE 'lms.%';
  IF n_owner <> n_ca THEN
    RAISE EXCEPTION 'LMS-L1: owner holds % lms keys, company_admin holds % — must match (owner-role.db.test.ts)', n_owner, n_ca;
  END IF;

  -- The header's argument, asserted: a DEPARTMENT HEAD must not be able to excuse their own team
  -- from the company's mandatory training. If a future change gives org_unit_lead this key, this
  -- is the line that should be revisited deliberately rather than discovered.
  SELECT count(*) INTO n_waive FROM role_permissions rp
    JOIN permissions p ON p.id = rp.permission_id JOIN roles r ON r.id = rp.role_id
   WHERE r.company_id IS NULL AND r.name = 'org_unit_lead' AND p.key = 'lms.enrollment.waive';
  IF n_waive <> 0 THEN
    RAISE EXCEPTION 'LMS-L1: org_unit_lead must NOT hold lms.enrollment.waive, found % row(s)', n_waive;
  END IF;
END $$;
`;

writeFileSync(join(ROOT, OUT), header);
console.log(`wrote ${OUT} — 2 roles, ${perms.length} permissions, ${bundleRows.length} bundle rows`);
