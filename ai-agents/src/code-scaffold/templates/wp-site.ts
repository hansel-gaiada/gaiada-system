// WSK-20 / WSK-D28 (webdesk-design-v2.md §08) + M6-P5a — the `siteKind: "wp"` template.
//
// ONE canonical theme: `webdesk/wordpress/theme/gaiada-webdesk/` (style.css, index.php,
// functions.php, inc/*, and a FIXTURE vendor/gaiada-sdk/sdk.php). This template emits exactly those
// files, with the scaffolded tenant's own generated `sdk.php` substituted for the fixture one.
//
// `ai-agents` and `webdesk` are separate standalone projects (repo root CLAUDE.md: "no monorepo,
// no shared package layer"), so the canonical files are vendored as strings in
// `wp-theme-files.generated.ts` (regenerate: `node scripts/sync-wp-theme.mjs`). The drift gate is
// `wp-site.test.ts`: it reads the canonical directory and asserts byte-for-byte equality (except
// sdk.php). The previous hand-written copy of the theme bootstrap (and its `page.php`, which read
// WordPress options and never emitted `inc/`) is gone.
import type { GeneratedFile } from "../page-composer";
import { WP_THEME_FILES } from "./wp-theme-files.generated";

export interface WpSiteTemplateArgs {
  tenantSlug: string;
  /** The PHP SDK's own generated bytes for this tenant (WSK-34's `sdk-php.mts` output), read from
   *  the pinned contract snapshot's `artifacts.sdkPhp` file — see `contract-snapshot-provider.ts`.
   *  Composed into `vendor/gaiada-sdk/sdk.php` verbatim, never re-derived or hand-edited here. */
  sdkPhpSource: string;
  contractVersion: string;
  vocabularyVersion: string;
}

export const WP_SDK_PATH = "vendor/gaiada-sdk/sdk.php";

/** The canonical theme files (everything but the SDK), identical for every tenant. */
export function wpThemeFiles(): GeneratedFile[] {
  return Object.entries(WP_THEME_FILES).map(([path, content]) => ({ path, content }));
}

/** The vendored PHP SDK — a plain file drop, never Composer (no shell on shared hosting). */
export function vendoredSdkPhp(args: WpSiteTemplateArgs): GeneratedFile {
  return { path: WP_SDK_PATH, content: args.sdkPhpSource };
}

export function themeReadme(args: WpSiteTemplateArgs): GeneratedFile {
  return {
    path: "README.md",
    content:
      `# Generated WebDesk theme (wp) — ${args.tenantSlug}\n\n` +
      `Scaffolded by \`code.scaffold\` v2's \`siteKind:"wp"\` template, pinned to contract ` +
      `v${args.contractVersion} / vocabulary v${args.vocabularyVersion}. The theme directory is the\n` +
      `canonical headless theme from \`webdesk/wordpress/theme/gaiada-webdesk/\`; \`vendor/gaiada-sdk/sdk.php\`\n` +
      `is this tenant's own generated PHP SDK.\n\n` +
      `## Configure (wp-config.php constants, or environment variables; never the database)\n\n` +
      `    define('GAIADA_WEBDESK_BASE_URL', 'https://<your WebDesk /v1 host>');\n` +
      `    define('GAIADA_WEBDESK_TENANT', '${args.tenantSlug}');\n` +
      `    define('GAIADA_WEBDESK_API_KEY', '<read key>');\n` +
      `    // optional: define('GAIADA_WEBDESK_LOCALES', 'en,id');  // first = default\n` +
      `    // optional: define('GAIADA_WEBDESK_ROUTES', '[{"pattern":"/blog/{slug}","collection":"article"}]');\n\n` +
      `Until the three required values are set, every page answers 503 "WebDesk is not configured".\n` +
      `Settings -> WebDesk shows the effective values (never the key) and a "Test connection" button.\n\n` +
      `## What this repo does NOT do\n\n` +
      `Composed and pushed by the agent-runner, never \`npm install\`/\`composer install\`/executed in\n` +
      `that process (WSK-D6). Activating the theme in wp-admin is an ops step this scaffold does not\n` +
      `perform. No caching layer (CDN purge is WSK-70).\n`,
  };
}

/** Composes every file the `wp` kind contributes. */
export function wpSiteFiles(args: WpSiteTemplateArgs): GeneratedFile[] {
  return [...wpThemeFiles(), vendoredSdkPhp(args), themeReadme(args)];
}
