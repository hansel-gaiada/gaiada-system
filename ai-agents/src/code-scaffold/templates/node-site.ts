/** The React block renderer. A pure string; the scaffolder never imports or runs it (WSK-D6). Written with
 *  String.raw so the regexes below reach the generated file unchanged; it holds no backtick and no dollar-brace. */
export function reactBlocksModule(): GeneratedFile {
  return {
    path: `${NODE_WEB_ROOT}/src/lib/blocks.tsx`,
    content: String.raw`// GENERATED by code.scaffold v2 (M6-P4b1) - a small server-component renderer for the /v1 block vocabulary.
// The Astro library @gaiada/webdesk-blocks cannot render in Next, so this is the Next-side equivalent:
//  - the renderer invariant: an unknown block type renders nothing and is reported, never thrown;
//  - output safety: links and images pass an allow-list, and nothing is injected as raw HTML (rich text is
//    shown as inert plain text);
//  - the draft banner and the locale-fallback notice.
// Not rendered yet (they resolve relations): featureGrid, form, faq, logoCloud. They are reported.
import { Fragment } from "react";
import { isBlockType } from "./block-types";

export { BLOCK_TYPE_NAMES, isBlockType } from "./block-types";

export interface RawBlock {
  type: string;
  props?: Record<string, unknown>;
}

export interface ItemEnvelope {
  collection: string;
  slug: string;
  locale: string;
  seo?: { title?: string; description?: string };
  meta?: { draft?: boolean; x?: Record<string, unknown> };
  blocks: RawBlock[];
}

type Props = Record<string, unknown>;
type Out = JSX.Element | null;

// ---- output safety (mirrors webdesk/blocks/src/safety.ts) ----
const SCHEME = /^[a-z][a-z0-9+.-]*:/i;
const IGNORED_IN_SCHEME_CHECK = /[\x00-\x20\x7f]+/g;
const CONTROL_CHARS = /[\x00-\x1f\x7f]+/g;
const RELATIVE_PATH = /^[^\\:/?#]+(?:[/?#][^\\]*)?$/;

function checkUrl(value: unknown, schemes: readonly string[], allowQueryOrFragment: boolean): string | undefined {
  if (typeof value !== "string") return undefined;
  const cleaned = value.replace(IGNORED_IN_SCHEME_CHECK, "");
  if (cleaned === "") return undefined;
  const scheme = SCHEME.exec(cleaned);
  if (scheme) {
    if (!schemes.includes(scheme[0].toLowerCase())) return undefined;
  } else if (cleaned.startsWith("/")) {
    if (cleaned[1] === "/" || cleaned[1] === "\\") return undefined;
  } else if (cleaned.startsWith("?") || cleaned.startsWith("#")) {
    if (!allowQueryOrFragment) return undefined;
  } else if (!RELATIVE_PATH.test(cleaned)) {
    return undefined;
  }
  return value.replace(CONTROL_CHARS, "").trim();
}

export function safeHref(value: unknown): string {
  return checkUrl(value, ["http:", "https:", "mailto:", "tel:"], true) ?? "#";
}

export function safeImgSrc(value: unknown): string | undefined {
  return checkUrl(value, ["http:", "https:"], false);
}

// ---- readers: block props arrive as unknown ----
function text(v: unknown): string | undefined {
  return typeof v === "string" && v.trim() !== "" ? v : undefined;
}

interface Media {
  url: string;
  alt: string;
  width?: number;
  height?: number;
}

function readMedia(v: unknown): Media | undefined {
  if (typeof v !== "object" || v === null) return undefined;
  const m = v as Record<string, unknown>;
  const url = safeImgSrc(m.url);
  if (!url) return undefined;
  return {
    url,
    alt: typeof m.alt === "string" ? m.alt : "",
    width: typeof m.width === "number" ? m.width : undefined,
    height: typeof m.height === "number" ? m.height : undefined,
  };
}

function nodeText(n: unknown): string {
  if (typeof n !== "object" || n === null) return "";
  const o = n as Record<string, unknown>;
  if (typeof o.text === "string") return o.text;
  return Array.isArray(o.children) ? o.children.map(nodeText).join("") : "";
}

/** Rich text as paragraphs of plain text. A string is split on blank lines; a { root } document yields one
 *  paragraph per top-level node. Markup is never interpreted. */
export function richTextParagraphs(v: unknown): string[] {
  if (typeof v === "string") {
    return v.split(/\n{2,}/).map((s) => s.trim()).filter((s) => s !== "");
  }
  if (typeof v === "object" && v !== null) {
    const root = (v as Record<string, unknown>).root;
    if (typeof root === "object" && root !== null) {
      const kids = (root as Record<string, unknown>).children;
      if (Array.isArray(kids)) return kids.map(nodeText).map((s) => s.trim()).filter((s) => s !== "");
    }
  }
  return [];
}

// ---- the blocks ----
export function Hero(props: Props): Out {
  const heading = text(props.heading);
  if (!heading) return null;
  const subheading = text(props.subheading);
  const media = readMedia(props.media);
  const ctaLabel = text(props.ctaLabel);
  const ctaHref = text(props.ctaHref);
  return (
    <section data-block-type="hero" className="py-12">
      <h1 className="text-4xl font-bold">{heading}</h1>
      {subheading ? <p className="mt-2 text-lg">{subheading}</p> : null}
      {media ? <img src={media.url} alt={media.alt} width={media.width} height={media.height} /> : null}
      {ctaLabel && ctaHref ? (
        <a className="mt-4 inline-block underline" href={safeHref(ctaHref)}>
          {ctaLabel}
        </a>
      ) : null}
    </section>
  );
}

export function RichText(props: Props): Out {
  const paragraphs = richTextParagraphs(props.content);
  if (paragraphs.length === 0) return null;
  return (
    <section data-block-type="richText" className="py-4">
      {paragraphs.map((p, i) => (
        <p key={i} className="mb-3">
          {p}
        </p>
      ))}
    </section>
  );
}

export function Gallery(props: Props): Out {
  const items = Array.isArray(props.items) ? props.items.map(readMedia).filter((m): m is Media => m !== undefined) : [];
  if (items.length === 0) return null;
  const caption = text(props.caption);
  return (
    <section data-block-type="gallery" className="py-4">
      <ul className="grid grid-cols-2 gap-2">
        {items.map((m, i) => (
          <li key={i}>
            <img src={m.url} alt={m.alt} width={m.width} height={m.height} />
          </li>
        ))}
      </ul>
      {caption ? <p className="mt-2 text-sm">{caption}</p> : null}
    </section>
  );
}

export function Cta(props: Props): Out {
  const heading = text(props.heading);
  const label = text(props.buttonLabel);
  if (!heading || !label) return null;
  const body = text(props.body);
  return (
    <section data-block-type="cta" className="py-8">
      <h2 className="text-2xl font-semibold">{heading}</h2>
      {body ? <p className="mt-2">{body}</p> : null}
      <a className="mt-4 inline-block rounded border px-4 py-2" href={safeHref(props.buttonHref)}>
        {label}
      </a>
    </section>
  );
}

export function Testimonial(props: Props): Out {
  const quote = richTextParagraphs(props.quote);
  const author = text(props.author);
  if (quote.length === 0 || !author) return null;
  const role = text(props.role);
  const avatar = readMedia(props.avatar);
  return (
    <section data-block-type="testimonial" className="py-6">
      <blockquote>
        {quote.map((p, i) => (
          <p key={i}>{p}</p>
        ))}
      </blockquote>
      {avatar ? <img src={avatar.url} alt={avatar.alt} width={avatar.width} height={avatar.height} /> : null}
      <p className="mt-2 font-semibold">
        {author}
        {role ? ", " + role : ""}
      </p>
    </section>
  );
}

export function DraftBanner(): Out {
  return (
    <div role="status" className="bg-yellow-100 px-4 py-2 text-sm">
      Draft preview: this content is not published.
    </div>
  );
}

export function LocaleFallbackNotice(props: { requested: string; served: string }): Out {
  return (
    <div role="status" className="bg-blue-50 px-4 py-2 text-sm">
      This page is not available in {props.requested}; showing {props.served}.
    </div>
  );
}

const RENDERERS: Record<string, (props: Props) => Out> = {
  hero: Hero,
  richText: RichText,
  gallery: Gallery,
  cta: Cta,
  testimonial: Testimonial,
};

function report(message: string, collection?: string, slug?: string): void {
  console.warn("[webdesk] " + message + (collection ? " (" + collection + "/" + (slug ?? "") + ")" : ""));
}

export function BlockRenderer(props: { blocks: RawBlock[]; collection?: string; slug?: string }): JSX.Element {
  const blocks = Array.isArray(props.blocks) ? props.blocks : [];
  return (
    <>
      {blocks.map((b, index) => {
        if (typeof b !== "object" || b === null || typeof b.type !== "string" || !isBlockType(b.type)) {
          report("unknown block type at index " + index + ", rendered nothing", props.collection, props.slug);
          return null;
        }
        if (b.type === "fields") return null; // known, non-visual: data for the site's own code
        const render = RENDERERS[b.type];
        if (!render) {
          report("block type " + b.type + " is not rendered by this renderer yet, rendered nothing", props.collection, props.slug);
          return null;
        }
        return <Fragment key={index}>{render(b.props ?? {})}</Fragment>;
      })}
    </>
  );
}

function readLocaleFallback(x: unknown): { requested: string; served: string } | null {
  if (typeof x !== "object" || x === null) return null;
  const v = (x as Record<string, unknown>).localeFallback;
  if (typeof v !== "object" || v === null) return null;
  const f = v as Record<string, unknown>;
  return typeof f.requested === "string" && typeof f.served === "string" ? { requested: f.requested, served: f.served } : null;
}

export function ItemRenderer(props: { envelope: ItemEnvelope }): JSX.Element {
  const { envelope } = props;
  const fallback = readLocaleFallback(envelope.meta?.x);
  return (
    <>
      {envelope.meta?.draft ? <DraftBanner /> : null}
      {fallback ? <LocaleFallbackNotice requested={fallback.requested} served={fallback.served} /> : null}
      <BlockRenderer blocks={envelope.blocks} collection={envelope.collection} slug={envelope.slug} />
    </>
  );
}
`,
  };
}
