// WSK-20 / M6-P4b1 - the `node` (fullstack) siteKind. A `node` repo is generated from the Next + Nest template
// (`webdesk/templates/fullstack-next-nest/`, WSK-D74): an npm workspace with `apps/web` (Next + Tailwind) and
// `apps/api` (Nest). The scaffolder fills ONLY `apps/web/`, plus `CONTRACT.lock` and `docs/` at the repo root.
// It never writes the workspace root (`package.json`, `.gitignore`, `README.md`, `.env.example`, compose, the
// site workflow) and never writes `apps/api/`: those belong to the template, and overwriting the root
// `package.json` would break the workspace.
//
// ── BLOCKS: A REACT RENDERER, NOT THE ASTRO LIBRARY (decision, M6-P4b1) ─────────────────────────────
// `@gaiada/webdesk-blocks` is an Astro component library (`.astro` files, `peerDependencies: astro`). A Next
// app cannot render `.astro` components, and vendoring the tarball into `apps/web/vendor/` would add a dead
// dependency that Next never imports. So the `node` kind vendors the generated TS SDK (types only, shared
// with astro) and emits a small server-component renderer for the same /v1 block vocabulary,
// `apps/web/src/lib/blocks.tsx`. It keeps the renderer invariant (an unknown block renders nothing and is
// reported), the output-safety rules (`safeHref`/`safeImgSrc`, no raw HTML), the draft banner and the
// locale-fallback notice. Because the `node` kind does not consume the library, a snapshot without one does
// NOT refuse a node site (scaffold.ts refuses only the kinds that vendor it).
// KNOWN GAP: it renders hero, richText (as inert plain text), gallery, cta and testimonial. featureGrid,
// form, faq and logoCloud resolve relations and need a real React build of the library; they render nothing
// and are reported, never faked.
import type { GeneratedFile } from "../page-composer";
import { sdkPackageJson } from "../git-writer";

export const NODE_WEB_ROOT = "apps/web";

/** The areas a `node` scaffold may write: the Next app, the lock, and the docs copy of the PRD/prototype. */
export const NODE_ALLOWED_PREFIXES: readonly string[] = [`${NODE_WEB_ROOT}/`, "docs/"];
export const NODE_ALLOWED_FILES: readonly string[] = ["CONTRACT.lock"];

export function isNodeAllowedPath(path: string): boolean {
  return NODE_ALLOWED_FILES.includes(path) || NODE_ALLOWED_PREFIXES.some((p) => path.startsWith(p));
}

