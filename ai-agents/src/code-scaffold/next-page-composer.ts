// M6-P4b1 - the `node` kind's page composer: a PrototypeSpec becomes Next (App Router) pages under
// `apps/web/src/app/`, fed by the ONE typed SDK client (`apps/web/src/lib/webdesk-sdk.ts`) and rendered by the
// React block renderer (`apps/web/src/lib/blocks.tsx`). Same rules as page-composer.ts (the astro/wp twin):
// never invent an SDK call a page has no data source for, a vocabulary gap becomes a TODO page plus a
// schema-proposal draft.
//
// Every prototype-supplied string (a title, a collection key) reaches the generated source only through
// JSON.stringify, as a JSX expression: a prototype is untrusted input and must not be able to inject code.
// A page slug becomes a DIRECTORY name, so each segment is validated first (a slug such as "../x" would write
// outside `apps/web/src/app/`).
import type { VocabularyGap } from "./envelope";
import type { CollectionIndex } from "./openapi-index";
import { collectionExists } from "./openapi-index";
import type { PrototypePageSpec, PrototypeSpec } from "./prototype-spec";
import { buildSchemaProposalDraft, schemaProposalFilePath } from "./schema-gap";
import type { ComposeResult, GeneratedFile } from "./page-composer";
import { NODE_WEB_ROOT } from "./templates/node-site";

const APP_DIR = `${NODE_WEB_ROOT}/src/app`;
const SEGMENT = /^[A-Za-z0-9][A-Za-z0-9_-]*$/;

export class InvalidPageSlugError extends Error {
  constructor(public readonly slug: string) {
    super(`prototype page slug ${JSON.stringify(slug)} is not a safe route (each "/" segment must match ${SEGMENT.source})`);
    this.name = "InvalidPageSlugError";
  }
}

/** "" or "index" is the home page; otherwise a path of safe segments. */
function routeSegments(slug: string): string[] {
  if (slug === "" || slug === "index") return [];
  const trimmed = slug.replace(/^\/+|\/+$/g, "");
  const segs = trimmed.split("/");
  if (trimmed === "" || !segs.every((s) => SEGMENT.test(s))) throw new InvalidPageSlugError(slug);
  return segs;
}

function pageDir(segs: string[], extra: string[] = []): string {
  return [APP_DIR, ...segs, ...extra].join("/");
}

/** The relative import prefix from a page file `<dir>/page.tsx` up to `apps/web/src/`. */
function toSrc(dir: string): string {
  const depth = dir.slice(`${NODE_WEB_ROOT}/src/`.length).split("/").length;
  return "../".repeat(depth);
}

function staticPage(page: PrototypePageSpec): GeneratedFile {
  const segs = routeSegments(page.slug);
  const dir = pageDir(segs);
  const src = toSrc(dir);
  const title = JSON.stringify(page.title);
  return {
    path: `${dir}/page.tsx`,
    content: `// GENERATED by code.scaffold v2 (M6-P4b1) - static page, no bound collection.
import { Hero, Cta } from "${src}lib/blocks";

export const metadata = { title: ${title} };

export default function Page() {
  return (
    <main className="p-8">
      <Hero heading={${title}} />
      {/* TODO(webdesk): replace this placeholder Cta once real content/composition exists for this page. */}
      <Cta heading="Get in touch" buttonLabel="Contact us" buttonHref="/contact" />
    </main>
  );
}
`,
  };
}

function itemPage(page: PrototypePageSpec, collection: string): GeneratedFile {
  const segs = routeSegments(page.slug);
  const dir = pageDir(segs, ["[slug]"]);
  const src = toSrc(dir);
  return {
    path: `${dir}/page.tsx`,
    content: `// GENERATED by code.scaffold v2 (M6-P4b1) - item page bound to a collection.
import { notFound } from "next/navigation";
import { ItemRenderer, type ItemEnvelope } from "${src}lib/blocks";
import { getItem, WebdeskFetchError } from "${src}lib/webdesk-sdk";

// Rendered per request: the build has no WEBDESK_HOST to fetch from.
export const dynamic = "force-dynamic";

const COLLECTION = ${JSON.stringify(collection)};
const FALLBACK_TITLE = ${JSON.stringify(page.title)};

async function load(slug: string): Promise<ItemEnvelope> {
  try {
    return await getItem<ItemEnvelope>(COLLECTION, slug);
  } catch (err) {
    if (err instanceof WebdeskFetchError && err.status === 404) notFound();
    throw err;
  }
}

export async function generateMetadata({ params }: { params: { slug: string } }) {
  const envelope = await load(params.slug);
  return { title: envelope.seo?.title ?? FALLBACK_TITLE };
}

export default async function Page({ params }: { params: { slug: string } }) {
  const envelope = await load(params.slug);
  return (
    <main className="p-8">
      <ItemRenderer envelope={envelope} />
    </main>
  );
}
`,
  };
}

function listingPage(page: PrototypePageSpec, collection: string): GeneratedFile {
  const segs = routeSegments(page.slug);
  const dir = pageDir(segs);
  const src = toSrc(dir);
  const base = segs.length === 0 ? "" : "/" + segs.join("/");
  return {
    path: `${dir}/page.tsx`,
    content: `// GENERATED by code.scaffold v2 (M6-P4b1) - listing page for a collection.
import Link from "next/link";
import { listItems } from "${src}lib/webdesk-sdk";

// Rendered per request: the build has no WEBDESK_HOST to fetch from.
export const dynamic = "force-dynamic";

const COLLECTION = ${JSON.stringify(collection)};
const TITLE = ${JSON.stringify(page.title)};
const BASE = ${JSON.stringify(base)};

export const metadata = { title: TITLE };

interface ListEnvelope {
  items: { slug: string; seo?: { title?: string } }[];
}

export default async function Page() {
  const list = await listItems<ListEnvelope>(COLLECTION);
  return (
    <main className="p-8">
      <h1 className="text-3xl font-bold">{TITLE}</h1>
      <ul>
        {list.items.map((item) => (
          <li key={item.slug}>
            <Link href={BASE + "/" + encodeURIComponent(item.slug)}>{item.seo?.title ?? item.slug}</Link>
          </li>
        ))}
      </ul>
    </main>
  );
}
`,
  };
}

function todoGapPage(page: PrototypePageSpec, reference: string, kind: VocabularyGap["kind"], proposalFilePath: string): GeneratedFile {
  const dir = pageDir(routeSegments(page.slug));
  return {
    path: `${dir}/page.tsx`,
    content: `// GENERATED by code.scaffold v2 (M6-P4b1) - VOCABULARY GAP.
// The prototype page ${JSON.stringify(page.title)} references ${kind} ${JSON.stringify(reference)}, which the pinned
// contract snapshot does not have. This is never filled in with a hand-rolled fetch: a schema-proposal draft
// was written at ${proposalFilePath}; a human reviews and submits it (WSK-32) before this page can be finished.
export const metadata = { title: ${JSON.stringify("TODO - " + page.title)} };

export default function Page() {
  return (
    <main className="p-8">
      {/* TODO(webdesk): unresolved ${kind}, see the schema-proposal draft. */}
      <p>This page is pending a vocabulary/composition change ({${JSON.stringify(reference)}}).</p>
    </main>
  );
}
`,
  };
}

export function composeNextPages(spec: PrototypeSpec, index: CollectionIndex): ComposeResult {
  const files: GeneratedFile[] = [];
  const gaps: VocabularyGap[] = [];
  const referenced = new Set<string>();

  for (const page of spec.pages) {
    if (!page.collection) {
      files.push(staticPage(page));
      continue;
    }
    if (!collectionExists(index, page.collection)) {
      const proposalFilePath = `${NODE_WEB_ROOT}/${schemaProposalFilePath({ kind: "unknown-collection", reference: page.collection })}`;
      const stub = todoGapPage(page, page.collection, "unknown-collection", proposalFilePath);
      gaps.push({
        pageSlug: page.slug,
        kind: "unknown-collection",
        reference: page.collection,
        todoFilePath: stub.path,
        proposalFilePath,
      });
      files.push(stub);
      files.push({
        path: proposalFilePath,
        content:
          JSON.stringify(buildSchemaProposalDraft({ pageSlug: page.slug, kind: "unknown-collection", reference: page.collection }), null, 2) + "\n",
      });
      continue;
    }
    referenced.add(page.collection);
    files.push(page.isListing ? listingPage(page, page.collection) : itemPage(page, page.collection));
  }

  return { files, gaps, referencedCollections: [...referenced].sort() };
}
