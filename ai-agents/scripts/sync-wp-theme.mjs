#!/usr/bin/env node
// ai-agents/scripts/sync-wp-theme.mjs
//
// M6-P5a — regenerates src/code-scaffold/templates/wp-theme-files.generated.ts from the ONE
// canonical headless WordPress theme, ../webdesk/wordpress/theme/gaiada-webdesk/ (everything
// except vendor/gaiada-sdk/sdk.php, which a scaffolded site takes from its own tenant instead).
// ai-agents and webdesk are separate projects, so the canonical files are vendored as strings;
// templates/wp-site.test.ts is the drift gate (it fails if this output is stale).
//
//   node scripts/sync-wp-theme.mjs
import fs from "node:fs";
import path from "node:path";
import url from "node:url";

const here = path.dirname(url.fileURLToPath(import.meta.url));
const THEME = path.resolve(here, "..", "..", "webdesk", "wordpress", "theme", "gaiada-webdesk");
const DEST = path.resolve(here, "..", "src", "code-scaffold", "templates", "wp-theme-files.generated.ts");
const SDK = "vendor/gaiada-sdk/sdk.php";

function walk(dir, rel = "") {
  const out = [];
  for (const e of fs.readdirSync(path.join(dir, rel), { withFileTypes: true })) {
    const r = rel ? `${rel}/${e.name}` : e.name;
    if (e.isDirectory()) out.push(...walk(dir, r));
    else out.push(r);
  }
  return out;
}

// Git keeps these files LF; a Windows checkout may show CRLF. Normalise so both agree.
const files = walk(THEME).filter((p) => p !== SDK).sort();
const entries = files.map((p) => {
  const text = fs.readFileSync(path.join(THEME, p), "utf8").replace(/\r\n/g, "\n");
  return `  ${JSON.stringify(p)}: ${JSON.stringify(text)},`;
});
const out =
  `// GENERATED by scripts/sync-wp-theme.mjs from webdesk/wordpress/theme/gaiada-webdesk/ — DO NOT HAND-EDIT.\n` +
  `// Every file of the canonical headless WordPress theme except vendor/gaiada-sdk/sdk.php.\n` +
  `export const WP_THEME_FILES: Readonly<Record<string, string>> = {\n${entries.join("\n")}\n};\n`;
fs.writeFileSync(DEST, out, "utf8");
console.log(`wrote ${files.length} files to ${path.relative(process.cwd(), DEST)}`);
